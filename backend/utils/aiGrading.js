// backend/utils/aiGrading.js
const { GoogleGenAI } = require("@google/genai");

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * Grade student submission using Google Gemini AI with automatic retry on 429 rate limit.
 */
async function gradeWithAI(assignmentTitle, answerKey, studentAnswer, totalMarks = 100, maxRetries = 3) {
  const provider = (process.env.AI_PROVIDER || "gemini").toLowerCase();

  if (provider === "gemini") {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      console.warn("Gemini API key missing. Falling back to local scoring.");
      return null;
    }

    const ai = new GoogleGenAI({ apiKey });
    const modelName = process.env.GEMINI_MODEL || "gemini-2.5-flash";

    const prompt = `
You are an academic grading assistant. Evaluate the student's answer based on the assignment title and reference answer key.

Assignment Title:
${assignmentTitle}

Answer Key / Criteria:
${answerKey}

Student Submission:
${studentAnswer}

Maximum Total Marks: ${totalMarks}

Return your evaluation ONLY as a valid JSON object matching this schema:
{
  "marksObtained": <number>,
  "feedback": "<concise feedback explaining marks and areas for improvement>"
}
`;

    for (let attempt = 1; attempt <= maxRetries; attempt++) {
      try {
        const response = await ai.models.generateContent({
          model: modelName,
          contents: prompt,
          config: {
            responseMimeType: "application/json",
          },
        });

        const rawText = response.text ? response.text.trim() : "";
        const cleanText = rawText.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
        const parsed = JSON.parse(cleanText);

        return {
          marks: Math.min(Math.max(0, Number(parsed.marksObtained) || 0), totalMarks),
          feedback: parsed.feedback || "Automated feedback generated by Gemini AI.",
        };
      } catch (error) {
        const isRateLimit =
          error.message &&
          (error.message.includes("429") || error.message.includes("RESOURCE_EXHAUSTED"));

        if (isRateLimit && attempt < maxRetries) {
          console.warn(`[Gemini Rate Limit] 429 hit. Backing off for 12s before retry ${attempt}/${maxRetries}...`);
          await sleep(12000); // Wait 12 seconds to clear per-minute quota
          continue;
        }

        console.error("Gemini grading error:", error.message || error);
        return null; // Fallback to local keyword grading if all retries fail
      }
    }
  }

  return null;
}

module.exports = { gradeWithAI };